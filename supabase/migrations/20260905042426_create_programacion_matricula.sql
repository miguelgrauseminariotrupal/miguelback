-- Programación de secciones/cursos y matrícula. Mirrors bd.sql/sq2.sql.
-- Se agregan UNIQUE compuestos que el esquema de referencia no declara
-- explícitamente pero que evitan datos duplicados (mismo curso programado
-- dos veces en la misma sección, mismo alumno matriculado dos veces en la
-- misma sección).

create table public.mg_programacion_seccion (
  id_programacion_seccion bigint generated by default as identity primary key,
  id_seccion bigint not null unique references public.mg_seccion (id_seccion),
  id_docente_responsable bigint not null references public.mg_docente (id_docente),
  estado boolean not null default true
);

create index idx_mg_prog_seccion_docente on public.mg_programacion_seccion (id_docente_responsable);

create table public.mg_programacion_curso (
  id_programacion_curso bigint generated by default as identity primary key,
  id_programacion_seccion bigint not null references public.mg_programacion_seccion (id_programacion_seccion),
  id_curso bigint not null references public.mg_curso (id_curso),
  id_docente bigint not null references public.mg_docente (id_docente),
  estado boolean not null default true,
  unique (id_programacion_seccion, id_curso)
);

create index idx_mg_prog_curso_curso on public.mg_programacion_curso (id_curso);
create index idx_mg_prog_curso_docente on public.mg_programacion_curso (id_docente);

create table public.mg_matricula (
  id_matricula bigint generated by default as identity primary key,
  id_programacion_seccion bigint not null references public.mg_programacion_seccion (id_programacion_seccion),
  id_estudiante bigint not null references public.mg_estudiante (id_estudiante),
  fecha_matricula date not null default current_date,
  estado boolean not null default true,
  unique (id_programacion_seccion, id_estudiante)
);

create index idx_mg_matricula_estudiante on public.mg_matricula (id_estudiante);
